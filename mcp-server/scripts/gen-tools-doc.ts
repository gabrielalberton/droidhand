/**
 * Generates ../docs/tools.md from the tool catalog.
 *
 *   npm run docs:tools          # write the file
 *   node --import tsx scripts/gen-tools-doc.ts --check   # exit 1 if it is stale
 *
 * `renderToolsDoc()` is exported for the test that keeps the file in sync.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { z, type ZodTypeAny } from "zod";
import { CATALOG, CATALOG_AREAS, PLANNED_TOOLS, type ToolDef } from "../src/catalog.js";

export const TOOLS_DOC_PATH = fileURLToPath(new URL("../../docs/tools.md", import.meta.url));

/** One documented argument. */
export interface ParamDoc {
  name: string;
  type: string;
  optional: boolean;
  description?: string;
}

function numberBounds(s: z.ZodNumber): string {
  let int = false;
  let min: number | undefined;
  let max: number | undefined;
  for (const c of s._def.checks) {
    if (c.kind === "int") int = true;
    else if (c.kind === "min") min = c.value;
    else if (c.kind === "max") max = c.value;
  }
  const base = int ? "integer" : "number";
  if (min !== undefined && max !== undefined) return `${base} ${min}–${max}`;
  if (min !== undefined) return `${base} ≥ ${min}`;
  if (max !== undefined) return `${base} ≤ ${max}`;
  return base;
}

/** Human-readable type of a zod schema (unwrapping optional). */
export function describeType(schema: ZodTypeAny): string {
  if (schema instanceof z.ZodOptional) return describeType(schema.unwrap());
  if (schema instanceof z.ZodNumber) return numberBounds(schema);
  if (schema instanceof z.ZodString) return schema._def.checks.some((c) => c.kind === "url") ? "string (URL)" : "string";
  if (schema instanceof z.ZodBoolean) return "boolean";
  if (schema instanceof z.ZodEnum) return (schema.options as string[]).map((o) => `"${o}"`).join(" | ");
  if (schema instanceof z.ZodArray) {
    const len = schema._def.exactLength?.value;
    return `${describeType(schema.element)}[${len ?? ""}]`;
  }
  return schema._def.typeName ?? "unknown";
}

/** Flatten a tool's input shape into documented params (in declaration order). */
export function describeParams(tool: ToolDef): ParamDoc[] {
  return Object.entries(tool.input).map(([name, schema]) => ({
    name,
    type: describeType(schema),
    optional: schema.isOptional(),
    description: schema.description,
  }));
}

/** Escape text for a Markdown table cell. */
function cell(text: string): string {
  return text.replace(/\|/g, "\\|").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

function notes(t: ToolDef): string {
  const parts: string[] = [t.tier];
  if (t.confirm) parts.push("confirm on device");
  if (t.local) parts.push("local (host)");
  return parts.join(" · ");
}

/** Render the whole Markdown document. */
export function renderToolsDoc(): string {
  // Arguments that carry a description are documented once, up front.
  const shared = new Map<string, string>();
  for (const t of CATALOG) {
    for (const p of describeParams(t)) if (p.description && !shared.has(p.name)) shared.set(p.name, p.description);
  }

  const out: string[] = [
    "# DroidHand tools",
    "",
    "<!-- Generated by mcp-server/scripts/gen-tools-doc.ts (npm run docs:tools). Do not edit by hand. -->",
    "",
    `${CATALOG.length} MCP tools in ${CATALOG_AREAS.length} areas. Tools are forwarded to the phone unless marked ` +
      "**local (host)**, in which case the relay daemon handles them itself.",
    "",
    "Notes column: the risk **tier** recorded in the audit log; **confirm on device** means the app asks the user " +
      "to approve the action on the phone first.",
    "",
    "## Shared arguments",
    "",
  ];
  for (const [name, desc] of shared) out.push(`- \`${name}\`: ${desc}.`.replace(/\.\.$/, "."));
  out.push(
    "",
    "Every tool that is not local also accepts `display`; it is left out of the tables below.",
    "",
  );

  for (const area of CATALOG_AREAS) {
    out.push(`## ${area.title}`, "", area.summary, "", "| Tool | What it does | Inputs | Notes |", "| --- | --- | --- | --- |");
    for (const t of area.tools) {
      const params = describeParams(t).filter((p) => !(p.name === "display" && !t.local));
      const inputs = params.length
        ? params.map((p) => `\`${p.name}\` ${cell(p.type)}${p.optional ? " (optional)" : ""}`).join("<br>")
        : "—";
      out.push(`| \`${t.name}\` | ${cell(t.description)} | ${inputs} | ${notes(t)} |`);
    }
    out.push("");
  }
  if (PLANNED_TOOLS.length) {
    out.push("## Planned", "", "Designed but not implemented in the app yet, so they are not offered to agents.", "",
      "| Tool | What it will do |", "| --- | --- |");
    for (const t of PLANNED_TOOLS) out.push(`| \`${t.name}\` | ${cell(t.description)} |`);
    out.push("");
  }
  return out.join("\n");
}

const isMain = process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) {
  const doc = renderToolsDoc();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(TOOLS_DOC_PATH, "utf8");
    } catch {
      /* missing counts as stale */
    }
    if (current !== doc) {
      process.stderr.write(`${TOOLS_DOC_PATH} is stale; run npm run docs:tools\n`);
      process.exit(1);
    }
  } else {
    writeFileSync(TOOLS_DOC_PATH, doc);
    process.stdout.write(`wrote ${TOOLS_DOC_PATH} (${CATALOG.length} tools)\n`);
  }
}
